//! Integration with macOS: PATH shims, the LaunchAgent, `/etc/resolver/<tld>`
//! and trusting the local CA. The last two need admin rights.

use crate::config::Config;
use crate::{caddy, download, paths, php, services};
use anyhow::{Context, bail};
use std::path::PathBuf;

pub const LABEL: &str = "dev.pack.daemon";

pub fn resolver_file(cfg: &Config) -> PathBuf {
    PathBuf::from(format!("/etc/resolver/{}", cfg.tld))
}

pub fn resolver_contents(cfg: &Config) -> String {
    format!("# Added by Pack\nnameserver 127.0.0.1\nport {}\n", cfg.dns_port)
}

pub fn resolver_ok(cfg: &Config) -> bool {
    std::fs::read_to_string(resolver_file(cfg)).is_ok_and(|s| s == resolver_contents(cfg))
}

pub fn ca_trusted() -> bool {
    let cert = caddy::root_cert();
    if !cert.exists() {
        return false;
    }
    std::process::Command::new("/usr/bin/security")
        .args(["verify-cert", "-c"])
        .arg(&cert)
        .output()
        .is_ok_and(|o| o.status.success())
}

/// Make sure Caddy's local CA exists (it is created lazily) and return its root.
pub async fn ensure_ca() -> anyhow::Result<PathBuf> {
    let cert = caddy::root_cert();
    if !cert.exists() {
        reqwest::get(format!("http://{}/pki/ca/local", caddy::ADMIN))
            .await
            .context("Caddy is not running")?
            .error_for_status()?;
    }
    if !cert.exists() {
        bail!("Caddy did not create its local CA");
    }
    Ok(cert)
}

/// Shell commands that need root, as one script.
pub fn privileged_script(cfg: &Config, ca: Option<&std::path::Path>) -> String {
    let mut script = format!(
        "mkdir -p /etc/resolver && printf '%s' '{}' > {}",
        resolver_contents(cfg),
        resolver_file(cfg).display()
    );
    if let Some(ca) = ca {
        script.push_str(&format!(
            " && security add-trusted-cert -d -r trustRoot -k /Library/Keychains/System.keychain '{}'",
            ca.display()
        ));
    }
    script
}

/// Run a root script with the macOS admin password dialog (used by the app).
pub async fn run_privileged_gui(script: &str) -> anyhow::Result<()> {
    let escaped = script.replace('\\', "\\\\").replace('"', "\\\"");
    let apple = format!("do shell script \"{escaped}\" with administrator privileges with prompt \"Pack needs to set up .test domains and HTTPS.\"");
    let out = tokio::process::Command::new("/usr/bin/osascript").arg("-e").arg(apple).output().await?;
    if !out.status.success() {
        bail!("{}", String::from_utf8_lossy(&out.stderr).trim());
    }
    Ok(())
}

/// Run a root script through sudo in the terminal (used by `pack install`).
pub fn run_privileged_tty(script: &str) -> anyhow::Result<()> {
    let status = std::process::Command::new("/usr/bin/sudo").args(["/bin/sh", "-c", script]).status()?;
    if !status.success() {
        bail!("sudo failed");
    }
    Ok(())
}

fn write_script(name: &str, body: &str) -> anyhow::Result<()> {
    let path = paths::bin().join(name);
    std::fs::write(&path, format!("#!/bin/sh\n# Generated by Pack\n{body}\n"))?;
    download::make_executable(&path)?;
    Ok(())
}

fn symlink(link: &str, target: &std::path::Path) -> anyhow::Result<()> {
    let path = paths::bin().join(link);
    let _ = std::fs::remove_file(&path);
    std::os::unix::fs::symlink(target, path)?;
    Ok(())
}

/// (Re)create everything in `bin/`: pack itself, php/composer/laravel shims,
/// versioned php binaries and service clients.
pub fn write_shims(cfg: &Config) -> anyhow::Result<()> {
    std::fs::create_dir_all(paths::bin())?;
    if let Ok(exe) = std::env::current_exe() {
        let exe = exe.canonicalize().unwrap_or(exe);
        if exe != paths::bin().join("pack") {
            symlink("pack", &exe)?;
        }
    }
    let home = paths::home();
    write_script("php", "exec \"$(dirname \"$0\")/pack\" exec-php -- \"$@\"")?;
    for p in php::installed() {
        write_script(
            &format!("php{}", p.version.replace('.', "")),
            &format!("exec \"$(dirname \"$0\")/pack\" exec-php --version {} -- \"$@\"", p.version),
        )?;
    }
    let composer_home = home.join("composer");
    write_script(
        "composer",
        &format!(
            "export COMPOSER_HOME=\"${{COMPOSER_HOME:-{}}}\"\nexec \"$(dirname \"$0\")/php\" \"{}\" \"$@\"",
            composer_home.display(),
            composer_phar().display()
        ),
    )?;
    write_script(
        "laravel",
        &format!(
            "export COMPOSER_HOME=\"${{COMPOSER_HOME:-{0}}}\"\n\
             if [ ! -f \"$COMPOSER_HOME/vendor/bin/laravel\" ]; then \"$(dirname \"$0\")/composer\" global require laravel/installer --quiet || exit 1; fi\n\
             exec \"$(dirname \"$0\")/php\" \"$COMPOSER_HOME/vendor/bin/laravel\" \"$@\"",
            composer_home.display()
        ),
    )?;
    for inst in &cfg.services {
        if !services::is_installed(inst) {
            continue;
        }
        for (link, target) in services::client_binaries(inst) {
            if target.exists() {
                symlink(&link, &target)?;
            }
        }
    }
    Ok(())
}

pub fn composer_phar() -> PathBuf {
    crate::packages::current("composer", "2").join("composer.phar")
}

pub async fn ensure_composer() -> anyhow::Result<()> {
    crate::packages::install("composer", "2", None).await?;
    Ok(())
}

pub fn launch_agent_path() -> PathBuf {
    paths::user_home().join(format!("Library/LaunchAgents/{LABEL}.plist"))
}

/// Install a LaunchAgent so the daemon starts at login and stays up.
pub fn install_launch_agent() -> anyhow::Result<()> {
    let exe = paths::bin().join("pack");
    let log = paths::logs().join("daemon.log");
    let plist = format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>{LABEL}</string>
  <key>ProgramArguments</key><array><string>{}</string><string>daemon</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>{}</string>
  <key>StandardErrorPath</key><string>{}</string>
</dict>
</plist>
"#,
        exe.display(),
        log.display(),
        log.display()
    );
    let path = launch_agent_path();
    std::fs::create_dir_all(path.parent().unwrap())?;
    std::fs::write(&path, plist)?;
    let uid = unsafe { libc::getuid() };
    let _ = std::process::Command::new("launchctl").args(["bootout", &format!("gui/{uid}/{LABEL}")]).output();
    let out = std::process::Command::new("launchctl")
        .args(["bootstrap", &format!("gui/{uid}")])
        .arg(&path)
        .output()?;
    if !out.status.success() {
        bail!("launchctl bootstrap failed: {}", String::from_utf8_lossy(&out.stderr));
    }
    Ok(())
}

/// Add Pack's bin dir to PATH in ~/.zshrc (idempotent).
pub fn add_to_path() -> anyhow::Result<bool> {
    let rc = paths::user_home().join(".zshrc");
    let line = format!("export PATH=\"{}:$PATH\" # Pack", paths::bin().display());
    let current = std::fs::read_to_string(&rc).unwrap_or_default();
    if current.contains(&line) {
        return Ok(false);
    }
    let mut next = current;
    if !next.is_empty() && !next.ends_with('\n') {
        next.push('\n');
    }
    next.push_str(&format!("\n{line}\n"));
    std::fs::write(rc, next)?;
    Ok(true)
}
