//! Shims on the user's PATH (`pack`, `php`, `php84`, `composer`, `laravel`,
//! database clients) and the local HTTPS certificate authority.

use crate::config::Config;
use crate::{caddy, download, packages, paths, php, platform, services};
use anyhow::{Context, bail};
use std::path::{Path, PathBuf};

/// Make sure Caddy's local CA exists (it is created lazily) and return its root.
pub async fn ensure_ca() -> anyhow::Result<PathBuf> {
    let cert = caddy::root_cert();
    if !cert.exists() {
        reqwest::get(format!("http://{}/pki/ca/local", caddy::ADMIN))
            .await
            .context("Caddy is not running")?
            .error_for_status()?;
    }
    if !cert.exists() {
        bail!("Caddy did not create its local CA");
    }
    Ok(cert)
}

pub fn ca_trusted() -> bool {
    platform::ca_trusted(&caddy::root_cert())
}

/// Everything that needs admin rights in one go: DNS routing, low ports and
/// trusting the HTTPS root. Runs with the OS dialog (`gui`) or sudo.
pub async fn configure_system(cfg: &Config, gui: bool) -> anyhow::Result<()> {
    let ca = ensure_ca().await.ok().filter(|_| !ca_trusted());
    if let Some(script) = platform::privileged_script(cfg, ca.as_deref()) {
        if gui {
            platform::run_privileged_gui(&script).await?;
        } else {
            platform::run_privileged_tty(&script)?;
        }
    }
    if let Some(ca) = &ca {
        platform::trust_ca_user(ca)?;
    }
    Ok(())
}

pub fn composer_phar() -> PathBuf {
    packages::current("composer", "2").join("composer.phar")
}

pub async fn ensure_composer() -> anyhow::Result<()> {
    packages::install("composer", "2", None).await?;
    Ok(())
}

/// The pack binary the shims call.
fn pack_exe() -> PathBuf {
    std::env::current_exe().ok().and_then(|e| e.canonicalize().ok()).unwrap_or_else(|| PathBuf::from("pack"))
}

fn command_line(program: &Path, args: &[String]) -> String {
    std::iter::once(format!("\"{}\"", program.display()))
        .chain(args.iter().map(|a| format!("\"{a}\"")))
        .collect::<Vec<_>>()
        .join(" ")
}

/// A small launcher: `#!/bin/sh` on Unix, `.cmd` on Windows, forwarding all arguments.
fn write_shim(name: &str, program: &Path, args: &[String]) -> anyhow::Result<()> {
    let line = command_line(program, args);
    if cfg!(windows) {
        std::fs::write(paths::bin().join(format!("{name}.cmd")), format!("@echo off\r\n{line} %*\r\n"))?;
    } else {
        let path = paths::bin().join(name);
        std::fs::write(&path, format!("#!/bin/sh\n# Generated by Pack\nexec {line} \"$@\"\n"))?;
        download::make_executable(&path)?;
    }
    Ok(())
}

/// (Re)create everything in `bin/`.
pub fn write_shims(cfg: &Config) -> anyhow::Result<()> {
    std::fs::create_dir_all(paths::bin())?;
    let pack = pack_exe();
    write_shim("pack", &pack, &[])?;
    write_shim("php", &pack, &["exec-php".into(), "--".into()])?;
    for p in php::installed() {
        write_shim(
            &format!("php{}", p.version.replace('.', "")),
            &pack,
            &["exec-php".into(), "--version".into(), p.version.clone(), "--".into()],
        )?;
    }
    let composer_home = paths::home().join("composer");
    let phar = composer_phar().display().to_string();
    if cfg!(windows) {
        std::fs::write(
            paths::bin().join("composer.cmd"),
            format!(
                "@echo off\r\nif not defined COMPOSER_HOME set \"COMPOSER_HOME={}\"\r\n\"{}\" exec-php -- \"{phar}\" %*\r\n",
                composer_home.display(),
                pack.display()
            ),
        )?;
        std::fs::write(
            paths::bin().join("laravel.cmd"),
            format!(
                "@echo off\r\nif not defined COMPOSER_HOME set \"COMPOSER_HOME={0}\"\r\n\
                 if not exist \"%COMPOSER_HOME%\\vendor\\bin\\laravel\" call \"%~dp0composer.cmd\" global require laravel/installer --quiet\r\n\
                 \"{1}\" exec-php -- \"%COMPOSER_HOME%\\vendor\\bin\\laravel\" %*\r\n",
                composer_home.display(),
                pack.display()
            ),
        )?;
    } else {
        let script = |body: String| {
            format!(
                "#!/bin/sh\n# Generated by Pack\nexport COMPOSER_HOME=\"${{COMPOSER_HOME:-{}}}\"\n{body}\n",
                composer_home.display()
            )
        };
        let composer = paths::bin().join("composer");
        std::fs::write(&composer, script(format!("exec \"{}\" exec-php -- \"{phar}\" \"$@\"", pack.display())))?;
        download::make_executable(&composer)?;
        let laravel = paths::bin().join("laravel");
        std::fs::write(
            &laravel,
            script(format!(
                "if [ ! -f \"$COMPOSER_HOME/vendor/bin/laravel\" ]; then \"$(dirname \"$0\")/composer\" global require laravel/installer --quiet || exit 1; fi\n\
                 exec \"{}\" exec-php -- \"$COMPOSER_HOME/vendor/bin/laravel\" \"$@\"",
                pack.display()
            )),
        )?;
        download::make_executable(&laravel)?;
    }
    for inst in &cfg.services {
        if !services::is_installed(inst) {
            continue;
        }
        for (link, target) in services::client_binaries(inst) {
            if target.exists() {
                write_shim(&link, &target, &[])?;
            }
        }
    }
    Ok(())
}

pub fn add_to_path() -> anyhow::Result<bool> {
    platform::add_to_path(&paths::bin())
}
