//! Caddy is Pack's web server: it serves every site, terminates HTTPS with
//! its internal CA and talks FastCGI to the PHP-FPM pools.

use crate::config::Config;
use crate::packages;
use crate::paths;
use crate::sites::{self, Site};
use crate::supervisor::Spec;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::PathBuf;

pub const ADMIN: &str = "127.0.0.1:20190";

pub fn binary() -> PathBuf {
    packages::current("caddy", "2").join("caddy")
}

pub async fn install() -> anyhow::Result<()> {
    packages::install("caddy", "2", None).await?;
    Ok(())
}

fn env() -> BTreeMap<String, String> {
    let mut env = BTreeMap::new();
    env.insert("XDG_DATA_HOME".into(), paths::caddy_dir().join("data").display().to_string());
    env.insert("XDG_CONFIG_HOME".into(), paths::caddy_dir().join("config").display().to_string());
    env
}

pub fn caddyfile_path() -> PathBuf {
    paths::caddy_dir().join("Caddyfile")
}

pub fn spec() -> Spec {
    Spec {
        name: "caddy".into(),
        program: binary(),
        args: vec![
            "run".into(),
            "--config".into(),
            caddyfile_path().display().to_string(),
            "--adapter".into(),
            "caddyfile".into(),
        ],
        env: env(),
        cwd: Some(paths::caddy_dir()),
        log: paths::logs().join("caddy.log"),
    }
}

/// The local CA root that has to be trusted for HTTPS sites.
pub fn root_cert() -> PathBuf {
    paths::caddy_dir().join("data/caddy/pki/authorities/local/root.crt")
}

fn q(s: impl std::fmt::Display) -> String {
    format!("\"{}\"", s.to_string().replace('"', "\\\""))
}

pub fn render(cfg: &Config) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Generated by Pack — edits are overwritten.\n{{\n\
         \tadmin {ADMIN}\n\
         \thttp_port {}\n\
         \thttps_port {}\n\
         \tlocal_certs\n\
         \tskip_install_trust\n\
         \tauto_https disable_redirects\n\
         \tlog {{\n\t\toutput file {}\n\t\tlevel WARN\n\t}}\n}}\n",
        cfg.http_port,
        cfg.https_port,
        q(paths::logs().join("caddy-errors.log").display())
    );
    // Caddy has to listen on all interfaces (macOS only lets non-root processes
    // bind low ports on the wildcard address), so refuse non-local clients.
    let _ = writeln!(out, "(local_only) {{\n\t@outside not remote_ip 127.0.0.0/8 ::1\n\tabort @outside\n}}\n");
    for site in sites::all(cfg) {
        let hosts = |scheme: &str| format!("{scheme}://{}, {scheme}://*.{}", site.host, site.host);
        if site.secured {
            let port = if cfg.https_port == 443 { String::new() } else { format!(":{}", cfg.https_port) };
            let _ = writeln!(out, "{} {{\n\tredir https://{{host}}{port}{{uri}}\n}}\n", hosts("http"));
            let _ = writeln!(out, "{} {{\n{}}}\n", hosts("https"), body(cfg, &site));
        } else {
            let _ = writeln!(out, "{} {{\n{}}}\n", hosts("http"), body(cfg, &site));
        }
    }
    let _ = writeln!(
        out,
        "http:// {{\n\theader Content-Type text/html\n\trespond <<HTML\n\t\t<!doctype html><title>Pack</title><body style=\"font:16px system-ui;padding:4rem;color:#333\"><h1>No site here</h1><p>Pack doesn't serve <b>{{host}}</b>. Park a folder or run <code>pack link</code> in your project.</p>\n\t\tHTML 404\n}}"
    );
    out
}

fn body(cfg: &Config, site: &Site) -> String {
    let mut b = String::new();
    if !cfg.lan_access {
        let _ = writeln!(b, "\timport local_only");
    }
    if let Some(upstream) = &site.proxy {
        let _ = writeln!(b, "\treverse_proxy {}", q(upstream));
        return b;
    }
    let _ = writeln!(b, "\troot * {}", q(site.docroot.display()));
    let _ = writeln!(b, "\tencode zstd gzip");
    if site.serves_php() {
        let sock = paths::php_socket(&site.php);
        let _ = writeln!(b, "\tphp_fastcgi {} {{", q(format!("unix/{}", sock.display())));
        let _ = writeln!(b, "\t\tenv PACK_SITE {}", site.name);
        let _ = writeln!(b, "\t}}");
    }
    let _ = writeln!(b, "\tfile_server");
    b
}

/// Write the Caddyfile and, if Caddy is up, hot-reload it through the admin API.
pub async fn apply(cfg: &Config) -> anyhow::Result<()> {
    std::fs::create_dir_all(paths::caddy_dir())?;
    let text = render(cfg);
    std::fs::write(caddyfile_path(), &text)?;
    let res = reqwest::Client::new()
        .post(format!("http://{ADMIN}/load"))
        .header("Content-Type", "text/caddyfile")
        .body(text)
        .send()
        .await;
    if let Ok(res) = res {
        if !res.status().is_success() {
            anyhow::bail!("caddy rejected the config: {}", res.text().await.unwrap_or_default());
        }
    }
    Ok(())
}
